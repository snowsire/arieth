def artwork_css():
    targets = ['.fs-featured-genres-module-genre-container',
               '.snow-genre-tile', '.fs-item-card-module-genre-placeholder']
    common = ',\n'.join('body ' + target + '::after' for target in targets)
    css = [MARKER, common + ''' {
  content: '';
  position: absolute;
  inset: 0;
  z-index: -1;
  pointer-events: none;
  background-position: right center;
  background-size: cover;
  background-repeat: no-repeat;
  opacity: 0.9;
}
body .fs-featured-genres-module-genre-container::before,
body .snow-genre-tile::before { display: none; }
body .fs-item-card-module-genre-placeholder { position: relative; overflow: hidden; }
body .fs-featured-genres-module-genre-name,
body .fs-item-card-module-genre-placeholder-text,
.snow-genre-tile strong { text-shadow: 0 2px 14px #09061299; }
''']
    named = []
    for index, (name, shapes) in enumerate(PATTERNS.items(), 1):
        svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 180">' + shapes + '</svg>'
        image = 'url("data:image/svg+xml,' + quote(svg, safe='') + '")'
        fallback = ',\n'.join('body ' + target + ':nth-child(6n+' + str(index) + ')::after' for target in targets)
        css.append(fallback + ' { background-image: ' + image + '; }\n')
        explicit = ',\n'.join('body ' + target + '[data-snow-genre-art="' + name + '"]::after' for target in targets)
        named.append(explicit + ' { background-image: ' + image + '; }\n')
    return '\n'.join(css + named)


def main():
    target = ROOT / 'home-discovery.css'
    current = target.read_text(encoding='utf-8')
    updated = current.split(MARKER)[0].rstrip() + '\n\n' + artwork_css()
    if '--check' in sys.argv:
        if current != updated:
            raise SystemExit('Genre artwork is stale; run python genre-art.py')
        print('Genre artwork is current: six local SVG patterns')
    else:
        target.write_text(updated, encoding='utf-8')
        print('Generated six genre artwork patterns')


if __name__ == '__main__':
    main()
